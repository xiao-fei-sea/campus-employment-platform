def check_existing_data():
    totals = {}
    with engine.connect() as conn:
        for table in TABLE_ORDER:
            result = conn.execute(text(f"SELECT COUNT(*) FROM {table}"))
            totals[table] = result.scalar()
    return totals


def clear_existing_data():
    print("\n" + "!" * 65)
    print("  WARNING: This will DELETE ALL existing data in ALL tables!")
    print("!" * 65)
    print()
    print("  Tables to be cleared:")
    totals = check_existing_data()
    for table in TABLE_ORDER:
        count = totals.get(table, 0)
        marker = f"  ({count} records)" if count > 0 else "  (empty)"
        print(f"    - {table} {marker}")
    print()
    ans = input("  Continue and CLEAR ALL DATA? (yes/no) [no]: ").strip().lower()
    if ans not in ('yes', 'y'):
        print("  Aborted by user.\n")
        sys.exit(0)

    print("\n  clearing...")
    with engine.connect() as conn:
        conn.execute(text("SET FOREIGN_KEY_CHECKS = 0"))
        for table in TABLE_ORDER:
            conn.execute(text(f"DELETE FROM {table}"))
        conn.execute(text("SET FOREIGN_KEY_CHECKS = 1"))
        conn.commit()
    print("  all tables cleared successfully.\n")
    print("=" * 65 + "\n")



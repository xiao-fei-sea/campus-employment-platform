def generate_applications(db: Session, students: list, jobs: list, resumes: list):
    print(f"\n[7/8] generating {SCALE['applications']} applications...")

    status_pools = {
        EmploymentStatus.SIGNED:    {"pending": 5, "viewed": 10, "passed": 15, "failed": 15, "offered": 35, "rejected": 15, "withdrawn": 5},
        EmploymentStatus.OFFERED:   {"pending": 10, "viewed": 15, "passed": 15, "failed": 15, "offered": 25, "rejected": 15, "withdrawn": 5},
        EmploymentStatus.SEARCHING: {"pending": 30, "viewed": 25, "passed": 15, "failed": 20, "offered": 5, "rejected": 5, "withdrawn": 0},
        EmploymentStatus.UNEMPLOYED:{"pending": 40, "viewed": 25, "passed": 10, "failed": 15, "offered": 2, "rejected": 8, "withdrawn": 0},
        EmploymentStatus.FURTHER_STUDY: {"pending": 50, "viewed": 30, "passed": 5, "failed": 10, "offered": 0, "rejected": 5, "withdrawn": 0},
        EmploymentStatus.STARTUP:   {"pending": 30, "viewed": 20, "passed": 15, "failed": 20, "offered": 5, "rejected": 10, "withdrawn": 0},
    }

    used_pairs = set()
    max_combinations = len(students) * len(jobs)
    count = 0
    for i in range(SCALE["applications"]):
        if (i + 1) % 500 == 0:
            print(f"  ... {i+1}/{SCALE['applications']}")

        for _ in range(100):
            student = random.choice(students)
            job = random.choice(jobs)
            pair = (student.id, job.id)
            if pair not in used_pairs:
                used_pairs.add(pair)
                break
        else:
            if len(used_pairs) >= max_combinations:
                print(f"  all {max_combinations} combinations exhausted, stopping at {count}")
                break
            continue

        student_resumes = [r for r in resumes if r.student_id == student.id]
        if not student_resumes:
            continue
        resume = random.choice(student_resumes)

        pool = status_pools.get(student.employment_status, status_pools[EmploymentStatus.SEARCHING])
        statuses, weights = zip(*[(ApplicationStatus(k), v) for k, v in pool.items()])
        app_status = random.choices(statuses, weights=weights)[0]

        days_ago = random.randint(1, 180)
        applied_at = datetime.now() - timedelta(days=days_ago)

        app = Application(
            student_id=student.id,
            job_id=job.id,
            resume_id=resume.id,
            status=app_status,
            cover_letter=f"尊敬的招聘负责人：\n\n我是{student.name}，{student.college}{student.major}专业{student.graduation_year}届毕业生。我对贵公司{job.title}岗位非常感兴趣。\n\n期待加入贵公司！",
            interview_time=applied_at + timedelta(days=random.randint(3, 14)) if app_status in [ApplicationStatus.PASSED, ApplicationStatus.OFFERED] else None,
            interview_location=job.address if app_status in [ApplicationStatus.PASSED, ApplicationStatus.OFFERED] else None,
            offer_salary=random.randint(8000, 35000) if app_status == ApplicationStatus.OFFERED else None,
            feedback=random.choice(["简历通过筛选", "面试表现优秀", "专业技能匹配"] if app_status in [ApplicationStatus.PASSED, ApplicationStatus.OFFERED] else [None, "等待HR筛选"]),
            viewed_at=applied_at + timedelta(hours=random.randint(2, 72)) if app_status != ApplicationStatus.PENDING else None,
            created_at=applied_at,
            updated_at=datetime.now() - timedelta(days=random.randint(0, 30)),
        )
        db.add(app)
        count += 1

        if (i + 1) % 500 == 0:
            db.commit()
    db.commit()
    print(f"  done: {count} applications")
    return count


